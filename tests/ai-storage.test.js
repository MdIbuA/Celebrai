const EVENT = {
  name: 'Anees Wedding', category: 'wedding', date: '2027-02-14', location: 'Coimbatore',
  guestCount: 250, budget: 800000, reservePercent: 10, theme: 'Temple traditional',
  cultural: 'Muslim ceremony, nikah in the morning', dietary: 'Halal only, one Jain counter',
  accessibility: 'Wheelchair ramp needed', nonNegotiables: 'Nikah must be before 11am',
  optionalPreferences: 'Live sweet counter if budget allows',
};

function fakeStore() {
  const map = new Map();
  return {
    getItem: (k) => (map.has(k) ? map.get(k) : null),
    setItem: (k, v) => map.set(k, String(v)),
    removeItem: (k) => map.delete(k),
    _set: (k, v) => map.set(k, v),
  };
}

describe('AI response validation', () => {
  const valid = {
    summary: 'A plan.',
    assumptions: ['a'],
    budgetWeights: { venue: 25, catering: 30 },
    tasks: [{ title: 'Book venue', description: 'd', daysBefore: 90, priority: 'high', budgetCategory: 'venue' }],
    vendorChecklist: [{ category: 'Venue', whatToAskFor: 'terms', typicalLeadTimeDays: 90 }],
    themeRecommendations: ['t'], foodSuggestions: ['f'], activitySuggestions: ['x'],
    risks: [{ risk: 'r', mitigation: 'm', severity: 'high' }],
    costSavingAlternatives: ['c'], outstandingQuestions: ['q'],
  };

  it('accepts a well-formed response', () => {
    const res = validatePlanResponse(valid);
    assert.ok(res.ok, JSON.stringify(res.errors));
    assert.equal(res.value.budgetWeights.length, 2);
  });

  it('rejects malformed JSON text', () => {
    const res = validatePlanResponse('{ not json');
    assert.ok(!res.ok);
    assert.ok(res.errors[0].includes('not valid JSON'));
  });

  it('rejects a response missing budget weights', () => {
    const { budgetWeights, ...rest } = valid;
    assert.ok(!validatePlanResponse(rest).ok);
  });

  it('rejects a response missing a summary', () => {
    assert.ok(!validatePlanResponse({ ...valid, summary: '   ' }).ok);
  });

  it('rejects an array or a primitive in place of an object', () => {
    assert.ok(!validatePlanResponse([1, 2]).ok);
    assert.ok(!validatePlanResponse(42).ok);
    assert.ok(!validatePlanResponse(null).ok);
  });

  it('drops out-of-range weights instead of trusting them', () => {
    const res = validatePlanResponse({ ...valid, budgetWeights: { venue: 25, catering: 900 } });
    assert.ok(!res.ok, 'an invalid weight fails the response');
  });

  it('silently drops malformed tasks rather than crashing', () => {
    const res = validatePlanResponse({
      ...valid,
      tasks: [
        { title: 'Good', daysBefore: 30 },
        { title: '', daysBefore: 30 },
        { title: 'Bad offset', daysBefore: -5 },
        { title: 'Way out', daysBefore: 99999 },
        'not an object',
      ],
    });
    assert.ok(res.ok);
    assert.equal(res.value.tasks.length, 1);
    assert.equal(res.value.tasks[0].title, 'Good');
  });

  it('never lets a model-supplied currency amount through', () => {
    const res = validatePlanResponse({
      ...valid,
      budgetAllocation: { catering: 450000 },
      totalCost: 999999,
      tasks: [{ title: 'T', daysBefore: 10, cost: 50000 }],
    });
    assert.ok(res.ok);
    assert.equal(res.value.budgetAllocation, undefined, 'unknown money keys dropped');
    assert.equal(res.value.totalCost, undefined);
    assert.equal(res.value.tasks[0].cost, undefined, 'per-task cost dropped');
  });

  it('normalises an unknown priority to medium', () => {
    const res = validatePlanResponse({ ...valid, tasks: [{ title: 'T', daysBefore: 5, priority: 'URGENT!!' }] });
    assert.equal(res.value.tasks[0].priority, 'medium');
  });
});

describe('planner behaviour', () => {
  it('builds a context without leaking the event name or exact budget', () => {
    const ctx = buildPlanningContext(EVENT);
    assert.equal(ctx.eventName, undefined, 'event name is not sent');
    assert.equal(ctx.budget, undefined, 'exact budget is not sent');
    assert.equal(ctx.budgetBand, '5L-15L');
    assert.equal(ctx.guestCount, 250);
    assert.ok(ctx.availableCategoryIds.includes('catering'));
  });

  it('returns a labelled demo plan when no endpoint is configured', async () => {
    const res = await requestPlan(EVENT, { endpoint: null });
    assert.equal(res.source, 'demo');
    assert.ok(res.notice.toLowerCase().includes('demo'));
    assert.ok(!res.notice.toLowerCase().includes('generated by a language model'));
  });

  it('demo plan passes the same schema validation as a live one', () => {
    const plan = buildDemoPlan(EVENT);
    const asModelShape = {
      ...plan,
      budgetWeights: Object.fromEntries(plan.budgetWeights.map((w) => [w.key, w.weight])),
    };
    assert.ok(validatePlanResponse(asModelShape).ok);
  });

  it('demo plan reacts to the actual event inputs', () => {
    const plan = buildDemoPlan(EVENT);
    assert.ok(plan.risks.some((r) => r.risk.includes('Accessibility')), 'accessibility risk raised');
    const tight = buildDemoPlan({ ...EVENT, budget: 40000, guestCount: 300 });
    assert.ok(tight.risks.some((r) => r.severity === 'high' && r.risk.includes('band')), 'budget-per-head risk raised');
  });

  it('throws a typed error when the service returns an invalid plan', async () => {
    const fetchImpl = async () => ({
      ok: true,
      json: async () => ({ plan: { summary: 'x' } }),
    });
    let caught = null;
    try {
      await requestPlan(EVENT, { endpoint: '/api/plan', fetchImpl });
    } catch (err) { caught = err; }
    assert.ok(caught instanceof PlanError);
    assert.equal(caught.kind, 'schema');
    assert.ok(caught.details.length > 0);
  });

  it('throws on an HTTP error and on a network failure', async () => {
    let caught = null;
    try {
      await requestPlan(EVENT, { endpoint: '/api/plan', fetchImpl: async () => ({ ok: false, status: 503 }) });
    } catch (e) { caught = e; }
    assert.equal(caught.kind, 'http');

    caught = null;
    try {
      await requestPlan(EVENT, { endpoint: '/api/plan', fetchImpl: async () => { throw new Error('offline'); } });
    } catch (e) { caught = e; }
    assert.equal(caught.kind, 'network');
  });

  it('accepts a valid live response', async () => {
    const fetchImpl = async () => ({
      ok: true,
      json: async () => ({
        plan: {
          summary: 'Live plan', budgetWeights: { venue: 30, catering: 40 },
          assumptions: [], tasks: [], vendorChecklist: [], risks: [],
          themeRecommendations: [], foodSuggestions: [], activitySuggestions: [],
          costSavingAlternatives: [], outstandingQuestions: [],
        },
      }),
    });
    const res = await requestPlan(EVENT, { endpoint: '/api/plan', fetchImpl });
    assert.equal(res.source, 'live');
    assert.equal(res.plan.summary, 'Live plan');
  });
});

describe('storage resilience', () => {
  it('returns an empty state when nothing is stored', () => {
    const { state, status } = loadState(fakeStore());
    assert.equal(status, 'empty');
    assert.equal(state.event, null);
  });

  it('recovers from corrupt JSON without losing the app', () => {
    const store = fakeStore();
    store._set(STORAGE_KEY, '{"event": {broken');
    const { state, status } = loadState(store);
    assert.equal(status, 'corrupt');
    assert.equal(state.event, null);
    assert.ok(store.getItem('celebrai.corrupt-backup'), 'corrupt data backed up');
  });

  it('ignores a stored primitive or array', () => {
    const store = fakeStore();
    store._set(STORAGE_KEY, '"just a string"');
    assert.equal(loadState(store).status, 'corrupt');
    store._set(STORAGE_KEY, '[1,2,3]');
    assert.equal(loadState(store).status, 'corrupt');
  });

  it('repairs individual malformed fields instead of discarding everything', () => {
    const store = fakeStore();
    store._set(STORAGE_KEY, JSON.stringify({
      schemaVersion: 1,
      event: { name: 'Kept' },
      tasks: 'not-an-array',
      vendors: [{ id: 'v1' }, 'junk', 42],
      expenses: null,
    }));
    const { state, status } = loadState(store);
    assert.equal(status, 'partial');
    assert.equal(state.event.name, 'Kept');
    assert.deepEqual(state.tasks, []);
    assert.equal(state.vendors.length, 1);
  });

  it('refuses to load a newer schema version', () => {
    const store = fakeStore();
    store._set(STORAGE_KEY, JSON.stringify({ schemaVersion: 99, event: {} }));
    assert.equal(loadState(store).status, 'future-version');
  });

  it('reports quota failures instead of throwing', () => {
    const store = {
      getItem: () => null,
      setItem: () => { const e = new Error('full'); e.name = 'QuotaExceededError'; throw e; },
      removeItem: () => {},
    };
    const res = saveState(emptyState(), store);
    assert.ok(!res.ok);
    assert.ok(res.quota);
    assert.ok(res.message.includes('Export'));
  });

  it('falls back to memory when localStorage throws on probe', () => {
    const hostile = {
      getItem: () => { throw new Error('blocked'); },
      setItem: () => {},
      removeItem: () => {},
    };
    const { status } = loadState(hostile);
    assert.equal(status, 'unavailable');
  });
});

describe('export and import', () => {
  const populated = {
    ...emptyState(),
    event: { ...EVENT },
    vendors: [createVendor({ name: 'Hall A', categoryId: 'venue', quotedCost: 150000 })],
  };

  it('export payload carries the app marker and a disclaimer', () => {
    const payload = buildExport(populated);
    assert.equal(payload.app, 'CelebrAI');
    assert.ok(payload.disclaimer.includes('not confirmed vendor quotations'));
  });

  it('export strips credential-shaped keys at any depth', () => {
    const payload = buildExport({
      ...populated,
      plan: { summary: 's', apiKey: 'sk-live-123', nested: { authorization: 'Bearer x', keep: 1 } },
    });
    const json = JSON.stringify(payload);
    assert.ok(!json.includes('sk-live-123'), 'api key must not be exported');
    assert.ok(!json.includes('Bearer x'), 'auth header must not be exported');
    assert.ok(json.includes('"keep":1'), 'harmless data retained');
  });

  it('import round-trips its own export', () => {
    const res = validateImportedState(JSON.stringify(buildExport(populated)));
    assert.ok(res.ok, JSON.stringify(res.errors));
    assert.equal(res.value.event.category, 'wedding');
  });

  it('rejects a file from another app', () => {
    const res = validateImportedState(JSON.stringify({ app: 'SomethingElse', event: {} }));
    assert.ok(!res.ok);
  });

  it('rejects invalid JSON and missing event objects', () => {
    assert.ok(!validateImportedState('<<<not json>>>').ok);
    assert.ok(!validateImportedState(JSON.stringify({ app: 'CelebrAI' })).ok);
  });

  it('rejects an import whose event fails validation', () => {
    const bad = buildExport({ ...populated, event: { ...EVENT, guestCount: -10, budget: -5 } });
    const res = validateImportedState(JSON.stringify(bad));
    assert.ok(!res.ok);
    assert.ok(res.errors.some((e) => e.includes('guestCount')));
  });

  it('rejects a future schema version on import', () => {
    const res = validateImportedState(JSON.stringify({ app: 'CelebrAI', schemaVersion: 9, event: EVENT }));
    assert.ok(!res.ok);
  });

  it('strips secrets present in an imported file', () => {
    const payload = { app: 'CelebrAI', schemaVersion: 1, event: EVENT, plan: { summary: 's', apiKey: 'leak' } };
    const res = validateImportedState(JSON.stringify(payload));
    assert.ok(res.ok);
    assert.ok(!JSON.stringify(res.value).includes('leak'));
  });
});

describe('vendor records', () => {
  it('stamps AI-suggested vendors as unverified', () => {
    const v = createVendor({ name: 'Suggested Hall', categoryId: 'venue', source: 'ai-suggested' });
    assert.equal(v.verification, 'unverified-suggestion');
    assert.equal(vendorSummary([v]).unverified, 1);
  });

  it('rejects a negative quoted cost', () => {
    assert.throws(() => createVendor({ name: 'X', categoryId: 'venue', quotedCost: -1000 }));
  });

  it('maps booked vendors to actual spend and quoted ones to estimates', () => {
    const a = createVendor({ name: 'A', categoryId: 'venue', quotedCost: 100000, bookingStatus: 'booked' });
    const b = createVendor({ name: 'B', categoryId: 'catering', quotedCost: 200000, bookingStatus: 'enquired' });
    const c = createVendor({ name: 'C', categoryId: 'decor', quotedCost: 50000, bookingStatus: 'cancelled' });
    const expenses = vendorsToExpenses([a, b, c]);
    assert.equal(expenses.length, 2, 'cancelled vendor excluded');
    assert.equal(expenses.find((e) => e.categoryId === 'venue').kind, 'actual');
    assert.equal(expenses.find((e) => e.categoryId === 'catering').kind, 'estimate');
    assert.equal(expenses.find((e) => e.categoryId === 'venue').amountPaise, toPaise(100000));
  });

  it('rejects unknown status transitions', () => {
    const v = createVendor({ name: 'A', categoryId: 'venue' });
    assert.throws(() => updateVendor([v], v.id, { bookingStatus: 'maybe' }));
    const ok = updateVendor([v], v.id, { bookingStatus: 'booked' });
    assert.equal(ok[0].bookingStatus, 'booked');
  });
});
